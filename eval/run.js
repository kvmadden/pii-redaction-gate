#!/usr/bin/env node
// eval/run.js — run the labeled synthetic development set through the engine
// and report per-type recall, per-token precision, hard-negative survival,
// and per-call latency, for every profile.
//
//   node eval/run.js                 # print the report; writes nothing
//   node eval/run.js --rounds 50     # fewer timing rounds
//   node eval/run.js --write         # also overwrite eval/results.json and .md
//
// The committed eval/results.* files are the FIRST RELEASE report (engine at
// 91c4e16, 70.5% recall). They are kept as that historical record, so the
// default run prints instead of overwriting them. The set is development data:
// later rules were changed while looking at it.
//
// Every profile is run with an EMPTY people map, so names are caught only by
// the unknown-name heuristic (identifiers, strict) or not at all (light,
// standard). See README "Evidence" for how to read the numbers.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { redactText } from "../src/engine.js";
import { DATASET } from "./dataset.js";
import { scoreSnippet, aggregate, percentile } from "./score.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const roundsArg = args.indexOf("--rounds");
const ROUNDS = roundsArg >= 0 ? Number(args[roundsArg + 1]) : 200;
const WARMUP = 20;
const PROFILES = ["identifiers", "strict", "standard", "light"];
const PRIMARY = "identifiers";
const EMPTY_MAP = { people: [], safe: [] };

const TYPE_ORDER = ["NAME", "RELATIVE", "FACILITY", "DOB", "DATE", "AGE", "PHONE", "EMAIL", "ADDRESS", "ID"];
const CAT_ORDER = ["DRUG", "DOSE", "LAB", "VITAL", "CLINICAL", "OTHER"];

function runProfile(profile) {
  const scores = DATASET.map((entry) => {
    const r = redactText(entry.text, { profile, peopleMap: EMPTY_MAP });
    if (r.blocked) throw new Error(`unexpected block on ${entry.id}`);
    return scoreSnippet(entry, r.text);
  });
  return aggregate(scores);
}

function timeProfile(profile) {
  for (let w = 0; w < WARMUP; w++) for (const e of DATASET) redactText(e.text, { profile, peopleMap: EMPTY_MAP });
  const samples = [];
  for (let r = 0; r < ROUNDS; r++) {
    for (const e of DATASET) {
      const t0 = process.hrtime.bigint();
      redactText(e.text, { profile, peopleMap: EMPTY_MAP });
      samples.push(Number(process.hrtime.bigint() - t0) / 1000); // µs
    }
  }
  samples.sort((a, b) => a - b);
  return {
    calls: samples.length,
    p50_us: percentile(samples, 50),
    p95_us: percentile(samples, 95),
    p99_us: percentile(samples, 99),
    max_us: samples[samples.length - 1],
  };
}

const pct = (x) => (x === null || x === undefined ? "n/a" : `${(x * 100).toFixed(1)}%`);
const us = (x) => `${x.toFixed(1)} µs`;

const date = new Date().toISOString().slice(0, 10);
const env = { node: process.version, platform: os.platform(), arch: os.arch() };
const counts = DATASET.reduce((a, e) => ((a[e.kind] = (a[e.kind] || 0) + 1), a), {});

const results = { date, env, rounds: ROUNDS, warmup: WARMUP, snippets: DATASET.length, kinds: counts, profiles: {} };
for (const p of PROFILES) results.profiles[p] = { ...runProfile(p), latency: timeProfile(p) };

// ── markdown ─────────────────────────────────────────────────────────
const L = [];
L.push(`# Evaluation results`);
L.push("");
L.push(`Development data. Run ${date} · ${DATASET.length} synthetic snippets (${Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(", ")}) · Node ${env.node} on ${env.platform}/${env.arch} · empty people map · generated by \`npm run eval\``);
L.push("");
L.push(`## Summary by profile`);
L.push("");
L.push(`| Profile | Entity recall (full) | Partial | Span precision | Char precision | Char recall | Hard negatives kept | Negative-only snippets untouched | p50 | p95 |`);
L.push(`|---|---|---|---|---|---|---|---|---|---|`);
for (const p of PROFILES) {
  const o = results.profiles[p].overall;
  const lat = results.profiles[p].latency;
  L.push(`| ${p} | ${pct(o.entityRecall)} (${Math.round(o.entityRecall * o.entities)}/${o.entities}) | ${o.entityPartial} | ${pct(o.spanPrecision)} (${o.spansEmitted} spans) | ${pct(o.charPrecision)} | ${pct(o.charRecall)} | ${pct(o.hardNegativesKept)} (${o.hardNegatives}) | ${o.negativeIntact}/${o.negativeSnippets} | ${us(lat.p50_us)} | ${us(lat.p95_us)} |`);
}
L.push("");
const P = results.profiles[PRIMARY];
L.push(`## \`${PRIMARY}\` profile: recall by gold entity type`);
L.push("");
L.push(`| Type | Gold count | Fully redacted | Partial | Missed | Recall |`);
L.push(`|---|---|---|---|---|---|`);
for (const t of TYPE_ORDER) {
  const r = P.byType[t];
  if (r) L.push(`| ${t} | ${r.n} | ${r.full} | ${r.partial} | ${r.missed} | ${pct(r.recall)} |`);
}
L.push("");
L.push(`## \`${PRIMARY}\` profile: precision by emitted token`);
L.push("");
L.push(`| Token | Spans emitted | Covering gold PII | False positives | Precision |`);
L.push(`|---|---|---|---|---|`);
for (const [tok, r] of Object.entries(P.byToken).sort((a, b) => b[1].emitted - a[1].emitted)) {
  L.push(`| [${tok}] | ${r.emitted} | ${r.tp} | ${r.fp} | ${pct(r.precision)} |`);
}
L.push("");
L.push(`## \`${PRIMARY}\` profile: hard negatives`);
L.push("");
L.push(`| Category | Count | Kept intact | Damaged | Kept rate |`);
L.push(`|---|---|---|---|---|`);
for (const c of CAT_ORDER) {
  const r = P.byCategory[c];
  if (r) L.push(`| ${c} | ${r.n} | ${r.kept} | ${r.damaged} | ${pct(r.keptRate)} |`);
}
L.push("");
L.push(`## \`${PRIMARY}\` profile: every miss (${P.misses.length})`);
L.push("");
L.push(`| Snippet | Type | Value | Result |`);
L.push(`|---|---|---|---|`);
for (const m of P.misses) L.push(`| ${m.id} | ${m.type} | ${m.value} | ${m.status} |`);
L.push("");
L.push(`## \`${PRIMARY}\` profile: every false-positive span (${P.falsePositives.length})`);
L.push("");
L.push(`| Snippet | Token | Redacted text | Hit a hard negative |`);
L.push(`|---|---|---|---|`);
for (const f of P.falsePositives) L.push(`| ${f.id} | [${f.token}] | ${f.text} | ${f.hitsKeep ? "yes" : "no"} |`);
L.push("");
L.push(`## Recall by type, all profiles`);
L.push("");
L.push(`| Type | ${PROFILES.join(" | ")} |`);
L.push(`|---|${PROFILES.map(() => "---").join("|")}|`);
for (const t of TYPE_ORDER) {
  L.push(`| ${t} | ${PROFILES.map((p) => pct(results.profiles[p].byType[t]?.recall)).join(" | ")} |`);
}
L.push("");
L.push(`## Hard negatives kept, all profiles`);
L.push("");
L.push(`| Category | ${PROFILES.join(" | ")} |`);
L.push(`|---|${PROFILES.map(() => "---").join("|")}|`);
for (const c of CAT_ORDER) {
  L.push(`| ${c} | ${PROFILES.map((p) => pct(results.profiles[p].byCategory[c]?.keptRate)).join(" | ")} |`);
}
L.push("");
L.push(`Latency: ${ROUNDS} timed rounds over all ${DATASET.length} snippets per profile after ${WARMUP} warm-up rounds; one sample per redactText call, single process, nearest-rank percentiles.`);
L.push("");

const md = L.join("\n");
if (args.includes("--write")) {
  fs.writeFileSync(path.join(__dirname, "results.json"), JSON.stringify(results, null, 2) + "\n");
  fs.writeFileSync(path.join(__dirname, "results.md"), md);
}
process.stdout.write(md);
